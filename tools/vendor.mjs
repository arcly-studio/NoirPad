// Copies third-party browser files from node_modules into static/vendor/.
//
// The app has no build step: static/ is served as-is and vendor files are
// committed. Versions are pinned in package.json / package-lock.json; to
// update a library, bump it there, run `npm install && npm run vendor`
// and commit the result.
import fs from "node:fs";
import path from "node:path";

const ROOT = path.resolve(import.meta.dirname, "..");
const NM = path.join(ROOT, "node_modules");
const OUT = path.join(ROOT, "static", "vendor");

// [source in node_modules, destination in static/vendor]
const FILES = [
    ["markdown-it/dist/browser/markdown-it.umd.min.js", "markdown-it/markdown-it.min.js"],
    ["markdown-it/LICENSE", "markdown-it/LICENSE"],
    ["dompurify/dist/purify.min.js", "dompurify/purify.min.js"],
    ["dompurify/LICENSE", "dompurify/LICENSE"],
    // highlight.js "common" build: one file, ~40 languages, auto-detection
    ["@highlightjs/cdn-assets/highlight.min.js", "highlight/highlight.min.js"],
    ["@highlightjs/cdn-assets/LICENSE", "highlight/LICENSE"],
];

// UI fonts (variable woff2), latin + latin-ext only (Czech diacritics).
// fonts.css is generated from each package's own @font-face rules.
const FONTS = ["inter", "jetbrains-mono", "orbitron", "space-grotesk", "outfit", "unbounded"];

const packages = new Set();

function copy(from, to) {
    fs.mkdirSync(path.dirname(to), { recursive: true });
    fs.copyFileSync(from, to);
}

function packageOf(src) {
    const parts = src.split("/");
    return parts[0].startsWith("@") ? parts.slice(0, 2).join("/") : parts[0];
}

for (const [src, dst] of FILES) {
    copy(path.join(NM, src), path.join(OUT, dst));
    packages.add(packageOf(src));
}

const FACE_RE = /\/\* ([\w-]+) \*\/\s*(@font-face \{[^}]+\})/g;
let fontCss = "/* Generated by tools/vendor.mjs from @fontsource-variable/* - do not edit. */\n";
for (const font of FONTS) {
    const pkg = `@fontsource-variable/${font}`;
    const pkgDir = path.join(NM, pkg);
    const dir = path.join(OUT, "fonts", font);
    copy(path.join(pkgDir, "LICENSE"), path.join(dir, "LICENSE"));
    const css = fs.readFileSync(path.join(pkgDir, "index.css"), "utf8");
    for (const [, id, face] of css.matchAll(FACE_RE)) {
        if (!/-latin(-ext)?-wght-normal$/.test(id)) continue;
        copy(path.join(pkgDir, "files", `${id}.woff2`), path.join(dir, `${id}.woff2`));
        fontCss += face
            .replace(/font-family: '([^']+) Variable'/, "font-family: '$1'")
            .replace("url(./files/", `url(${font}/`) + "\n";
    }
    packages.add(pkg);
}
fs.writeFileSync(path.join(OUT, "fonts", "fonts.css"), fontCss);

const versions = {};
for (const pkg of [...packages].sort()) {
    versions[pkg] = JSON.parse(fs.readFileSync(path.join(NM, pkg, "package.json"), "utf8")).version;
}
fs.writeFileSync(path.join(OUT, "VERSIONS.json"), JSON.stringify(versions, null, 2) + "\n");
console.log("vendored:", versions);
